package io.metaloom.loom.test.integration.node.docs;

import java.awt.image.BufferedImage;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;

import javax.imageio.ImageIO;

import io.metaloom.cortex.api.media.LoomMedia;
import io.metaloom.cortex.api.option.CortexOptions;
import io.metaloom.cortex.common.media.impl.LoomMediaImpl;
import io.metaloom.loom.test.TestEnvHelper;
import io.metaloom.loom.test.data.AudioData;
import io.metaloom.loom.test.data.DocData;
import io.metaloom.loom.test.data.ImageData;
import io.metaloom.loom.test.data.OtherData;
import io.metaloom.loom.test.data.TestDataCollection;
import io.metaloom.loom.test.data.TestMedia;
import io.metaloom.loom.test.data.VideoData;
import io.metaloom.video4j.Video4j;
import io.metaloom.video4j.VideoFile;
import io.metaloom.video4j.Videos;

/**
 * What a recipe is handed: the real test corpus and a scratch meta directory.
 *
 * <p>
 * There is deliberately no Loom client. Every node is run with {@code null} for it, which
 * {@code AbstractMediaNode} treats as offline mode: persistence no-ops and the asset lookup returns
 * nothing. The debugging view shows what a node <em>emitted on its ports</em>, which is unaffected,
 * and not needing a database or a server is what lets these fixtures be regenerated by anyone.
 * </p>
 */
public class FixtureEnv implements VideoData, ImageData, AudioData, DocData, OtherData {

	private final TestDataCollection data;

	public FixtureEnv() throws IOException {
		this.data = TestEnvHelper.prepareTestdata("docs-fixtures");
	}

	@Override
	public Path root() {
		return data.root();
	}

	/**
	 * A media handle for one of the corpus files, resolved through a neutral library path.
	 *
	 * <p>
	 * Several nodes emit {@code media.absolutePath()} on an output port — a filter emits it on the
	 * bucket it routed to, a source emits it on {@code media} — and that value is drawn verbatim on
	 * the node card. Run straight out of the test corpus it reads
	 * {@code /home/<someone>/workspaces/…/target/test-env-docs-fixtures/folderA/…}, which then ships
	 * to a public website carrying a developer's home directory and a build layout.
	 * </p>
	 *
	 * <p>
	 * So the corpus is linked into a plain library directory first and the nodes run from there. The
	 * path on the card is a real path to the real file the node really read — it just is not this
	 * machine's build tree. Hard-linked rather than copied: same filesystem, no second copy of a
	 * 36 MB clip, and a fallback to a copy if the link is refused.
	 * </p>
	 */
	public LoomMedia media(TestMedia media) throws IOException {
		return new LoomMediaImpl(inLibrary(media.path()));
	}

	/** The neutral root the recipes run from — also what the filesystem source enumerates. */
	public Path libraryRoot() throws IOException {
		return Files.createDirectories(Path.of(System.getProperty("java.io.tmpdir"), "loom-docs-library"));
	}

	/** Link (or copy) one corpus file into the library, and return where it landed. */
	public Path inLibrary(Path source) throws IOException {
		Path target = libraryRoot().resolve(source.getFileName().toString());
		if (Files.exists(target)) {
			return target;
		}
		try {
			Files.createLink(target, source);
		} catch (IOException | UnsupportedOperationException e) {
			Files.copy(source, target);
		}
		return target;
	}

	/** A media handle for a path outside the corpus. */
	public LoomMedia media(Path path) {
		return new LoomMediaImpl(path);
	}

	/**
	 * A frame of {@link #video1()} with two people in it — a café conversation, the man nearer the
	 * camera than the woman.
	 *
	 * <p>
	 * Chosen by looking, not by arithmetic: nothing in the corpus records which frames hold how many
	 * faces, so this is a fact about one file that a change of corpus would invalidate. The recipes
	 * that use it assert on what the detector found rather than assuming two, so a bad frame shows
	 * up as a thin picture rather than as a wrong one.
	 * </p>
	 */
	public static final int TWO_FACE_FRAME = 240;

	/**
	 * One real frame of the demo clip, written into the library as a still.
	 *
	 * <p>
	 * Three recipes need a picture with more than one person in it and need it to be
	 * <em>the same</em> picture: scene layout has to reason about a depth map and a set of boxes
	 * that describe one scene, and face description has to crop the faces those boxes name. A
	 * portrait would give each of them one object and nothing to relate it to, and the corpus has no
	 * group photograph — but the demo clip has frames with two people in them, and a frame of a real
	 * video is a real picture.
	 * </p>
	 *
	 * <p>
	 * Written once and reused across recipes: decoding 4K to seek a few hundred frames is slow, and
	 * the file has to keep one path anyway so that the depth map, the boxes and the descriptions all
	 * name the same media.
	 * </p>
	 */
	public Path frameStill(int frameIndex) throws IOException {
		Path still = libraryRoot().resolve("scene-frame-" + frameIndex + ".png");
		if (Files.exists(still)) {
			return still;
		}
		Video4j.init();
		Path source = inLibrary(video1().path());
		try (VideoFile video = Videos.open(source.toString())) {
			video.seekToFrame(frameIndex);
			BufferedImage image = video.frameToImage();
			if (image == null) {
				throw new IllegalStateException("Could not read frame " + frameIndex + " of " + source);
			}
			Path temp = Files.createTempFile("scene-frame", ".png");
			ImageIO.write(image, "png", temp.toFile());
			Files.move(temp, still, StandardCopyOption.REPLACE_EXISTING);
		}
		return still;
	}

	/**
	 * The corpus speech recording, as a WAV whisper can actually read.
	 *
	 * <p>
	 * Every video in the corpus is <strong>silent</strong> — stock footage, video stream only — and
	 * the one recording with speech in it, {@code jfk.webm}, is Opus in WebM with no duration in the
	 * container. {@code AudioExtractor.decodeAudioToPCM} hands whisper zero samples for it
	 * ("offset 0ms is past the end of the audio"), and whisper then reports success with an empty
	 * transcript — a green node that transcribed nothing, which is precisely the picture this
	 * harness must not publish.
	 * </p>
	 *
	 * <p>
	 * So the same audio is remuxed once, with ffmpeg, into the 16 kHz mono PCM whisper wants. The
	 * words are the real recording's; only the container changed.
	 * </p>
	 *
	 * @throws IllegalStateException when the remux fails — the caller's requirement should have
	 *         checked for ffmpeg first
	 */
	public Path speechWav() throws IOException, InterruptedException {
		Path wav = libraryRoot().resolve("jfk-16k-mono.wav");
		if (Files.exists(wav)) {
			return wav;
		}
		Path source = inLibrary(root().resolve("folderA/folderB/jfk.webm"));
		Path temp = Files.createTempFile("docs-speech", ".wav");
		Process ffmpeg = new ProcessBuilder("ffmpeg", "-y", "-v", "error", "-i", source.toString(),
			"-vn", "-ac", "1", "-ar", "16000", "-c:a", "pcm_s16le", temp.toString())
			.redirectErrorStream(true).start();
		String output = new String(ffmpeg.getInputStream().readAllBytes());
		if (ffmpeg.waitFor() != 0) {
			throw new IllegalStateException("Could not remux " + source + " to WAV: " + output);
		}
		Files.move(temp, wav, StandardCopyOption.REPLACE_EXISTING);
		return wav;
	}

	/** Is ffmpeg on the path? {@link #speechWav()} needs it. */
	public static boolean hasFfmpeg() {
		try {
			return new ProcessBuilder("ffmpeg", "-version").redirectErrorStream(true).start().waitFor() == 0;
		} catch (Exception e) {
			return false;
		}
	}

	/**
	 * Cortex options with a fresh meta path.
	 *
	 * <p>
	 * Fresh per node, because several nodes write their artifacts under it and key them by the
	 * media's hash — sharing one directory across recipes would let a second run of a node find the
	 * first run's file and report a cache hit, which is not what the picture is supposed to show.
	 * </p>
	 */
	public CortexOptions cortexOptions(String name) throws IOException {
		return new CortexOptions().setMetaPath(Files.createTempDirectory("docs-fixture-" + name));
	}

	/** Where the file actually is while the recipe runs — see {@link #media(TestMedia)}. */
	public String displayPath(TestMedia media) throws IOException {
		return inLibrary(media.path()).toString();
	}
}
