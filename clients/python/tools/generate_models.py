def collect() -> tuple[dict[str, list[JavaClass]], list[JavaEnum], dict[str, str]]:
    """Parse the Java tree into modules of classes, plus the enums and list element types."""
    modules: dict[str, list[JavaClass]] = {}
    enums: list[JavaEnum] = []
    element_types: dict[str, str] = {}

    for path in sorted(JAVA_MODEL_ROOT.rglob("*.java")):
        relative = path.relative_to(JAVA_MODEL_ROOT)
        package_suffix = ".".join(relative.parts[:-1])
        if package_suffix in SKIP_PACKAGES:
            continue
        if path.name.endswith("Examples.java"):
            continue

        classes, file_enums = parse_java_file(path)
        enums.extend(file_enums)

        module = module_name_for(package_suffix)
        for cls in classes:
            if cls.name in BASE_CLASSES:
                continue
            if cls.extends == "AbstractListResponse" and len(cls.extends_args) == 2:
                element_types[cls.name] = cls.extends_args[1].split(".")[-1]
            modules.setdefault(module, []).append(cls)

    for root in JAVA_EXTRA_ENUM_ROOTS:
        for path in sorted(root.rglob("*.java")):
            _, file_enums = parse_java_file(path)
            enums.extend(file_enums)

    return modules, enums, element_types


def build(check: bool) -> int:
    modules, all_enums, element_types = collect()

    model_module: dict[str, str] = {}
    for module, classes in modules.items():
        for cls in classes:
            model_module[cls.name] = module

    # Only the enums actually referenced by a field are worth emitting; the api tree
    # contains many that never reach the REST surface.
    referenced_types: set[str] = set()
    for classes in modules.values():
        for cls in classes:
            for f in cls.fields:
                for token in re.findall(r"\b(\w+)\b", f.java_type):
                    referenced_types.add(token)

    enums_by_name = {e.name: e for e in all_enums if e.constants}
    used_enums = sorted(
        (enums_by_name[name] for name in referenced_types if name in enums_by_name),
        key=lambda e: e.python_name,
    )
    enum_module = {e.python_name: "enums" for e in used_enums}
    enum_names = {e.name: e.python_name for e in used_enums}
    nested_enums = {(e.owner, e.name): e.python_name for e in used_enums if e.owner}

    mapper = TypeMapper(set(model_module), enum_names, nested_enums)

    outputs: dict[Path, str] = {}

    # enums.py
    enum_lines = [
        BANNER.rstrip(),
        '"""Wire enums.',
        "",
        "The server maps enums by their Java constant name, so the value of each member",
        "is the name itself. Unknown values from a newer server are passed through as",
        "plain strings rather than raising -- see ``models/base.py``.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from enum import Enum",
        "",
        "from .base import register",
        "",
        "",
    ]
    for enum in used_enums:
        enum_lines.extend(render_enum(enum))
    enum_lines.append("for _enum in (")
    enum_lines.extend(f"    {e.python_name}," for e in used_enums)
    enum_lines.append("):")
    enum_lines.append("    register(_enum)")
    outputs[OUTPUT_DIR / "enums.py"] = "\n".join(enum_lines) + "\n"

    # model modules
    for module, classes in sorted(modules.items()):
        classes = sorted(classes, key=lambda c: c.name)
        local_names = {c.name for c in classes}
        package = classes[0].package
        outputs[OUTPUT_DIR / f"{module}.py"] = render_module(
            module, package, classes, mapper, element_types, local_names, model_module, enum_module
        )

    # __init__.py
    exported: list[tuple[str, str]] = [(name, module) for name, module in model_module.items()]
    exported += [(e.python_name, "enums") for e in used_enums]
    outputs[OUTPUT_DIR / "__init__.py"] = render_package_init(sorted(exported))

    if mapper.unmapped:
        for entry in sorted(set(mapper.unmapped)):
            print(f"UNMAPPED {entry}", file=sys.stderr)
        print(
            f"\n{len(set(mapper.unmapped))} field(s) could not be mapped. Extend SCALARS or "
            f"OPAQUE_TYPES in this script rather than editing the generated output.",
            file=sys.stderr,
        )
        return 1

    coverage = render_coverage(modules, used_enums)

    if check:
        # Compare against what a fresh generate-then-format would produce, by writing
        # to a scratch copy rather than the tree.
        stale = [
            path
            for path, content in _formatted(outputs).items()
            if not path.exists() or path.read_text(encoding="utf-8") != content
        ]
        if COVERAGE_FILE.read_text(encoding="utf-8") != coverage:
            stale.append(COVERAGE_FILE)
        if stale:
            for path in stale:
                print(f"stale: {path.relative_to(CLIENT_ROOT)}", file=sys.stderr)
            print("\nRun: python3 tools/generate_models.py", file=sys.stderr)
            return 1
        print(f"up to date: {len(outputs)} modules")
        return 0

    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
    ruff_format(sorted(outputs))
    COVERAGE_FILE.write_text(coverage, encoding="utf-8")

    total_fields = sum(len(c.fields) for cs in modules.values() for c in cs)
    total_classes = sum(len(cs) for cs in modules.values())
    print(
        f"wrote {len(outputs)} modules: {total_classes} classes, "
        f"{len(used_enums)} enums, {total_fields} fields"
    )
    return 0


def _formatted(outputs: dict[Path, str]) -> dict[Path, str]:
    """Return what each module would look like after generation *and* formatting."""
    import tempfile

    with tempfile.TemporaryDirectory() as scratch:
        scratch_root = Path(scratch)
        mapping = {}
        for path, content in outputs.items():
            target = scratch_root / path.name
            target.write_text(content, encoding="utf-8")
            mapping[path] = target
        ruff_format(sorted(mapping.values()))
        return {path: target.read_text(encoding="utf-8") for path, target in mapping.items()}


def render_package_init(exported: list[tuple[str, str]]) -> str:
    hand_written = [
        "MODEL_REGISTRY",
        "CreatorEditorResponse",
        "CreatorEditorStatus",
        "GenericMessageResponse",
        "ListResponse",
        "MetaModel",
        "Model",
        "NamedReference",
        "PagingInfo",
        "Response",
        "UserReference",
        "format_instant",
        "parse_instant",
    ]
    lines = [
        BANNER.rstrip(),
        '"""Wire models for the Loom REST API.',
        "",
        "Every request and response body is a dataclass, flat-exported here::",
        "",
        "    from loom_client.models import AssetResponse, UserCreateRequest",
        "",
        "The shared machinery -- ``to_dict``/``from_dict``, name mapping, timestamp",
        "helpers -- lives in :mod:`loom_client.models.base` and is documented there.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
    ]
    by_module: dict[str, list[str]] = {"base": list(hand_written)}
    for name, module in exported:
        by_module.setdefault(module, []).append(name)
    # Sorted by module name so the block satisfies isort; ".base" is just another entry.
    for module, names in sorted(by_module.items()):
        joined = ",\n    ".join(sorted(names))
        lines.append(f"from .{module} import (\n    {joined},\n)")

    all_names = sorted({name for name, _ in exported} | set(hand_written))
    lines.append("")
    lines.append("__all__ = [")
    lines.extend(f'    "{name}",' for name in all_names)
    lines.append("]")
    return "\n".join(lines) + "\n"


def render_coverage(modules: dict[str, list[JavaClass]], enums: list[JavaEnum]) -> str:
    """A manifest of every Java field and where it landed.

    Committed so that a regeneration shows up as a reviewable diff even when the
    generated Python happens to be formatted identically.
    """
    lines = [
        "# Field coverage manifest, written by tools/generate_models.py.",
        "# Every Java model field and the Python attribute it became.",
        "# Review the diff of this file after regenerating.",
        "",
    ]
    for module, classes in sorted(modules.items()):
        for cls in sorted(classes, key=lambda c: c.name):
            base = BASE_CLASSES.get(cls.extends or "", "Model")
            lines.append(f"{module}.{cls.name} <- {cls.package}.{cls.name} ({base})")
            for f in cls.fields:
                name, alias = python_field_name(f.java_name)
                if f.json_name:
                    alias = f.json_name
                wire = alias or to_camel_case(name)
                lines.append(f"    {name} <- {f.java_type} {f.java_name} (wire: {wire})")
    lines.append("")
    for enum in sorted(enums, key=lambda e: e.python_name):
        source = f"{enum.owner}.{enum.name}" if enum.owner else enum.name
        lines.append(f"enums.{enum.python_name} <- {source}: {', '.join(enum.constants)}")
    return "\n".join(lines) + "\n"


def ruff_format(paths: list[Path]) -> None:
    """Format the emitted modules with ruff, if it is available.

    The output has to come out already formatted, or ``--check`` reports every module
    as stale the moment anyone runs ``./lint.sh``. Best effort: without ruff the code
    is still valid, just not normalised, and ``--check`` will say so.
    """
    ruff = shutil.which("ruff") or str(CLIENT_ROOT / ".venv/bin/ruff")
    if not Path(ruff).exists() and not shutil.which(ruff):
        print("ruff not found; generated modules are unformatted", file=sys.stderr)
        return
    subprocess.run(
        [ruff, "check", "--fix", "--quiet", *map(str, paths)],
        cwd=CLIENT_ROOT,
        check=False,
    )
    subprocess.run(
        [ruff, "format", "--quiet", *map(str, paths)],
        cwd=CLIENT_ROOT,
        check=False,
    )


