"""Regenerate ``loom_client/models/`` from the server's Java model classes.

The server's REST models are hand-written Java POJOs and the published OpenAPI
document carries no schemas, so there is nothing to generate a client from except
the Java sources themselves. Transcribing ~800 fields by hand would mean a
double-digit number of silent casing errors, so they are transcribed mechanically
and the output is committed.

Run it after the Java models change::

    python3 tools/generate_models.py           # rewrite loom_client/models/
    python3 tools/generate_models.py --check   # fail if the output is stale

This is not a build step. It is not imported by the package, and nothing in
``setup.sh``, ``test.sh`` or the Maven build invokes it.

What it does *not* do: parse Java properly. It is a line scanner, which is adequate
because these files are uniformly formatted POJOs — one ``private <Type> <name>;``
per field, annotations on their own lines. Anything it cannot map is reported as
UNMAPPED and fails the run rather than being silently dropped.
"""

