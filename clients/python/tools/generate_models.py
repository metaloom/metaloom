@dataclass
class JavaField:
    java_type: str
    java_name: str
    description: str | None = None
    json_name: str | None = None
    has_json_format: bool = False


@dataclass
class JavaClass:
    name: str
    package: str
    extends: str | None
    extends_args: list[str]
    fields: list[JavaField] = field(default_factory=list)


#: Nested enum names too generic to stand alone once flattened into ``enums.py``.
#: These get their owning class prepended: ``NodeRegistryEventMessage.Type`` would
#: otherwise be exported as plain ``Type``.
GENERIC_ENUM_NAMES = {"Type", "Reason", "Status", "State", "Kind", "Mode", "Level"}


@dataclass
class JavaEnum:
    name: str
    package: str
    constants: list[str] = field(default_factory=list)
    #: Enclosing class, for enums declared inside one.
    owner: str | None = None

    @property
    def python_name(self) -> str:
        if self.owner and self.name in GENERIC_ENUM_NAMES:
            owner = self.owner.removesuffix("Message").removesuffix("Response")
            return f"{owner}{self.name}"
        return self.name


