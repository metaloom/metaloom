CLASS_RE = re.compile(
    r"^public\s+(?:abstract\s+)?class\s+(\w+)"
    r"(?:\s*<[^>]*>)?"
    r"(?:\s+extends\s+([\w.]+)\s*(<[^{]*?>)?)?"
    r"(?:\s+implements\s+([^{]+))?",
)
ENUM_RE = re.compile(r"^\s*public\s+enum\s+(\w+)")
FIELD_RE = re.compile(
    r"^\s*private\s+(?!static)([\w.]+(?:\s*<[^;]*>)?(?:\s*\[\s*\])?)\s+(\w+)\s*(?:=[^;]*)?;"
)
PACKAGE_RE = re.compile(r"^package\s+([\w.]+);")
DESCRIPTION_RE = re.compile(r'@JsonPropertyDescription\("(.*)"\)')
JSON_PROPERTY_NAME_RE = re.compile(r'@JsonProperty\((?:value\s*=\s*)?"([^"]+)"')
JSON_FORMAT_RE = re.compile(r"@JsonFormat\(")


