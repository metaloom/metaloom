@dataclass
class Mapped:
    annotation: str
    default: str
    metadata: str | None = None
    note: str | None = None


class TypeMapper:
    def __init__(
        self,
        model_names: set[str],
        enum_names: dict[str, str],
        nested_enums: dict[tuple[str, str], str],
    ) -> None:
        self.models = model_names
        #: Java enum name -> Python enum name.
        self.enums = enum_names
        #: (owning class, Java enum name) -> Python enum name, for nested enums whose
        #: bare name was too generic to export as-is.
        self.nested_enums = nested_enums
        self.unmapped: list[str] = []

    def map_field(self, owner: str, f: JavaField) -> Mapped:
        annotation, default, note = self._map_type(owner, f.java_type, f)
        return Mapped(annotation=annotation, default=default, note=note)

    def _map_type(self, owner: str, java_type: str, f: JavaField) -> tuple[str, str, str | None]:
        if java_type in SCALARS:
            annotation, default = SCALARS[java_type]
            return annotation, default or "None", None

        if java_type == "Instant":
            # The server writes timestamps two ways: ISO strings where the field
            # carries @JsonFormat, epoch seconds where it does not.
            if f.has_json_format:
                return "str | None", "None", None
            return (
                "float | None",
                "None",
                "epoch seconds, not an ISO string -- see parse_instant()",
            )

        if java_type.endswith("[]"):
            inner = java_type[:-2]
            item, _, _ = self._map_type(owner, inner, f)
            return f"list[{_strip_optional(item)}]", "field(default_factory=list)", None

        collection = re.match(r"^(List|Set|Collection)<(.+)>$", java_type)
        if collection:
            item, _, note = self._map_type(owner, collection.group(2), f)
            return f"list[{_strip_optional(item)}]", "field(default_factory=list)", note

        mapping = re.match(r"^Map<(.+)>$", java_type)
        if mapping:
            args = split_generic_args(mapping.group(1))
            if len(args) == 2:
                value, _, note = self._map_type(owner, args[1], f)
                return f"dict[str, {_strip_optional(value)}]", "field(default_factory=dict)", note
            return "dict[str, Any]", "field(default_factory=dict)", None

        if java_type == "Object":
            return "Any", "None", None

        simple = java_type.split(".")[-1]

        if simple in OPAQUE_TYPES:
            return "dict[str, Any] | None", "None", f"opaque: {OPAQUE_TYPES[simple]}"

        # A nested enum shadows a same-named one elsewhere, so resolve it first.
        if nested := self.nested_enums.get((owner, simple)):
            return f"{nested} | None", "None", None

        if simple in self.enums:
            return f"{self.enums[simple]} | None", "None", None

        if simple in self.models:
            return f"{simple} | None", "None", None

        self.unmapped.append(f"{owner}.{f.java_name}: {java_type}")
        return "Any", "None", f"UNMAPPED Java type {java_type}"


def _strip_optional(annotation: str) -> str:
    return annotation.replace(" | None", "")


