def strip_comments(source: str) -> str:
    """Remove block and line comments.

    ``AssetResponse`` and friends carry commented-out fields; picking those up would
    invent attributes the server never sends.
    """
    source = re.sub(r"/\*.*?\*/", "", source, flags=re.DOTALL)
    return "\n".join(re.sub(r"//.*$", "", line) for line in source.splitlines())


def split_generic_args(text: str) -> list[str]:
    """Split ``LT, T`` or ``String, List<X>`` at top-level commas only."""
    args: list[str] = []
    depth = 0
    current = ""
    for char in text:
        if char == "<":
            depth += 1
        elif char == ">":
            depth -= 1
        if char == "," and depth == 0:
            args.append(current.strip())
            current = ""
        else:
            current += char
    if current.strip():
        args.append(current.strip())
    return args


def parse_java_file(path: Path) -> tuple[list[JavaClass], list[JavaEnum]]:
    raw = path.read_text(encoding="utf-8")
    source = strip_comments(raw)
    lines = source.splitlines()

    package = ""
    for line in lines:
        match = PACKAGE_RE.match(line.strip())
        if match:
            package = match.group(1)
            break

    classes: list[JavaClass] = []
    enums: list[JavaEnum] = []
    current: JavaClass | None = None
    pending_description: str | None = None
    pending_json_name: str | None = None
    pending_json_format = False

    index = 0
    while index < len(lines):
        line = lines[index]
        stripped = line.strip()

        enum_match = ENUM_RE.match(line)
        if enum_match:
            # An indented declaration is nested inside the class being parsed.
            owner = current.name if line.startswith((" ", "\t")) and current else None
            enums.append(_parse_enum(enum_match.group(1), package, lines, index, owner))
            index += 1
            continue

        class_match = CLASS_RE.match(stripped)
        if class_match:
            name, extends, generics, _implements = class_match.groups()
            args = split_generic_args(generics.strip()[1:-1]) if generics else []
            current = JavaClass(
                name=name,
                package=package,
                extends=extends.split(".")[-1] if extends else None,
                extends_args=args,
            )
            classes.append(current)
            index += 1
            continue

        if description := DESCRIPTION_RE.search(stripped):
            pending_description = description.group(1)
        if json_name := JSON_PROPERTY_NAME_RE.search(stripped):
            pending_json_name = json_name.group(1)
        if JSON_FORMAT_RE.search(stripped):
            pending_json_format = True

        field_match = FIELD_RE.match(line)
        if field_match and current is not None:
            java_type = re.sub(r"\s+", "", field_match.group(1))
            current.fields.append(
                JavaField(
                    java_type=java_type,
                    java_name=field_match.group(2),
                    description=pending_description,
                    json_name=pending_json_name,
                    has_json_format=pending_json_format,
                )
            )
            pending_description = None
            pending_json_name = None
            pending_json_format = False
        elif stripped and not stripped.startswith("@"):
            pending_description = None
            pending_json_name = None
            pending_json_format = False

        index += 1

    return classes, enums


def _parse_enum(name: str, package: str, lines: list[str], start: int, owner: str | None = None) -> JavaEnum:
    """Read an enum's constants.

    Constants run from the opening brace to the first top-level ``;`` (or the closing
    brace when the enum has no members beyond its constants). They may carry
    constructor arguments -- ``ReactionType`` declares ``SATISFIED("...", "...")`` --
    so the split has to respect parentheses.
    """
    text = "\n".join(lines[start:])
    body = text[text.index("{") + 1 :]

    depth = 0
    end = len(body)
    for index, char in enumerate(body):
        if char in "({[":
            depth += 1
        elif char in ")}]":
            if char == "}" and depth == 0:
                end = index
                break
            depth -= 1
        elif char == ";" and depth == 0:
            end = index
            break
    section = body[:end]

    constants: list[str] = []
    depth = 0
    current = ""
    for char in section + ",":
        if char in "({[":
            depth += 1
        elif char in ")}]":
            depth -= 1
        if char == "," and depth == 0:
            token = current.strip()
            if match := re.match(r"^([A-Z][A-Z0-9_]*)\s*(\(.*\))?$", token, re.DOTALL):
                constants.append(match.group(1))
            current = ""
        else:
            current += char

    return JavaEnum(name=name, package=package, constants=constants, owner=owner)


