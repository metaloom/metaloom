def python_field_name(java_name: str) -> tuple[str, str | None]:
    """Return the attribute name and an explicit wire alias when one is needed."""
    snake = to_snake_case(java_name)
    if snake in PYTHON_KEYWORDS or snake in RESERVED_ATTRIBUTES:
        return snake + "_", java_name
    # Only emit an alias when the default mapping would not round-trip.
    if to_camel_case(snake) != java_name:
        return snake, java_name
    return snake, None


#: Matches the ruff line-length configured in pyproject.toml, so the generated
#: modules pass ./lint.sh without a per-file exemption.
LINE_LENGTH = 110


def _wrap_comment(text: str, indent: str = "    ") -> list[str]:
    """Emit a ``#:`` comment, wrapped. Javadoc descriptions run long."""
    import textwrap

    width = LINE_LENGTH - len(indent) - 3
    return [f"{indent}#: {line}" for line in textwrap.wrap(text, width=width)] or [f"{indent}#:"]


def render_field(f: JavaField, mapped: Mapped) -> list[str]:
    name, alias = python_field_name(f.java_name)
    if f.json_name:
        alias = f.json_name

    lines: list[str] = []
    if f.description:
        lines.extend(_wrap_comment(f.description))
    if mapped.note:
        lines.extend(_wrap_comment(f"NOTE: {mapped.note}"))

    if alias:
        metadata = f'metadata={{"json": "{alias}"}}'
        if mapped.default.startswith("field("):
            default = mapped.default[:-1] + f", {metadata})"
        else:
            default = f"field(default={mapped.default}, {metadata})"
    else:
        default = mapped.default

    lines.append(f"    {name}: {mapped.annotation} = {default}")
    return lines


def render_enum(enum: JavaEnum) -> list[str]:
    qualified = f"{enum.package}.{enum.owner}.{enum.name}" if enum.owner else f"{enum.package}.{enum.name}"
    lines = [f"class {enum.python_name}(str, Enum):"]
    lines.append(f'    """Mirrors ``{qualified}``."""')
    lines.append("")
    for constant in enum.constants:
        lines.append(f'    {constant} = "{constant}"')
    lines.append("")
    lines.append("")
    return lines


def render_class(cls: JavaClass, mapper: TypeMapper, element_types: dict[str, str]) -> list[str]:
    base = BASE_CLASSES.get(cls.extends or "", "Model")

    lines = ["@dataclass", f"class {cls.name}({base}):"]
    doc = f'    """Mirrors ``{cls.package}.{cls.name}``."""'
    lines.append(doc)

    body: list[str] = []

    # A list response's element type comes from its `extends` generic arguments.
    if cls.extends == "AbstractListResponse":
        element = element_types.get(cls.name)
        if element:
            body.append("    #: Array which contains the found elements.")
            body.append(f"    data: list[{element}] = field(default_factory=list)")

    for f in cls.fields:
        body.extend(render_field(f, mapper.map_field(cls.name, f)))

    if not body:
        lines.append("")
    else:
        lines.append("")
        lines.extend(body)

    lines.append("")
    lines.append("")
    return lines


def _import_line(module: str, names: list[str], indent: str = "") -> str:
    """Render an import, wrapped in parentheses when it would run long."""
    flat = f"{indent}from {module} import {', '.join(names)}"
    if len(flat) <= LINE_LENGTH:
        return flat
    body = "".join(f"{indent}    {name},\n" for name in names)
    return f"{indent}from {module} import (\n{body}{indent})"


def render_module(
    module: str,
    package: str,
    classes: list[JavaClass],
    mapper: TypeMapper,
    element_types: dict[str, str],
    local_names: set[str],
    model_module: dict[str, str],
    enum_module: dict[str, str],
) -> str:
    rendered: list[str] = []
    for cls in classes:
        rendered.extend(render_class(cls, mapper, element_types))
    body = "\n".join(rendered).rstrip() + "\n"

    bases_used = sorted({BASE_CLASSES.get(cls.extends or "", "Model") for cls in classes})
    needs_field = "field(" in body
    needs_any = re.search(r"\bAny\b", body) is not None

    # Types from other model modules are imported only for type checkers: at runtime
    # they are resolved through the model registry, which keeps the generated modules
    # free of import cycles.
    # Collected from the annotations only. Scanning the rendered body would also pick
    # up type names that merely appear in a Javadoc-derived comment, and emit an
    # import nothing uses.
    annotated = " ".join(mapper.map_field(cls.name, f).annotation for cls in classes for f in cls.fields)
    annotated += " " + " ".join(element_types.get(cls.name, "") for cls in classes)
    referenced = {
        name
        for name in re.findall(r"\b([A-Z]\w+)\b", annotated)
        if name not in local_names and (name in model_module or name in enum_module)
    }
    external_models = sorted(n for n in referenced if n in model_module and model_module[n] != module)
    external_enums = sorted(n for n in referenced if n in enum_module)

    header = [
        BANNER.rstrip(),
        f'"""Mirrors ``{package}``."""',
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass" + (", field" if needs_field else ""),
    ]
    # Only cross-module *models* need the TYPE_CHECKING guard; enums are imported for
    # real, since they carry no risk of a cycle. Constants sort before classes, which
    # is the order isort expects.
    typing_imports = (["TYPE_CHECKING"] if external_models else []) + (["Any"] if needs_any else [])
    if typing_imports:
        header.append(f"from typing import {', '.join(typing_imports)}")
    header.append("")
    header.append(_import_line(".base", bases_used))

    if external_enums:
        header.append(_import_line(".enums", external_enums))

    if external_models:
        header.append("")
        header.append("if TYPE_CHECKING:")
        by_module: dict[str, list[str]] = {}
        for name in external_models:
            by_module.setdefault(model_module[name], []).append(name)
        for other, names in sorted(by_module.items()):
            header.append(_import_line(f".{other}", sorted(names), indent="    "))

    header.append("")
    header.append("")
    return "\n".join(header) + "\n" + body


