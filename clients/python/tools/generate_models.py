def to_snake_case(name: str) -> str:
    """``lastUuid`` -> ``last_uuid``, ``dbRevision`` -> ``db_revision``."""
    out = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name)
    out = re.sub(r"(?<=[A-Z])([A-Z][a-z])", r"_\1", out)
    return out.lower()


def to_camel_case(name: str) -> str:
    """Inverse of :func:`to_snake_case`, and the client's default wire mapping."""
    head, *rest = name.split("_")
    return head + "".join(word[:1].upper() + word[1:] for word in rest)


def module_name_for(package_suffix: str) -> str:
    """``asset.location.video`` -> ``asset_location_video``."""
    return package_suffix.replace(".", "_") or "root"


