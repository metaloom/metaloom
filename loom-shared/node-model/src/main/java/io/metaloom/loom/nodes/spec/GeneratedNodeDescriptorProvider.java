package io.metaloom.loom.nodes.spec;

import java.io.IOException;
import java.io.InputStream;
import java.util.List;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;

/**
 * Serves the built-in node contracts from a generated resource.
 *
 * <h2>Why a resource and not 29 hand-written classes</h2>
 *
 * <p>
 * Every one of these contracts is now declared on the node itself, with {@code @NodeSpec},
 * {@code @PortDoc} and {@code @ParamDoc} sitting on the very constants and fields the node executes
 * against. That is the only copy anyone edits.
 * </p>
 *
 * <p>
 * Loom, however, cannot reach those declarations: the node classes live in {@code cortex/}, which
 * {@code loom-shared} must not depend on — the dependency runs the other way, and inverting it would
 * drag every node's transitive native libraries into the server. So the harvest runs at
 * <strong>build time</strong>, in a module that can see both sides, and its output is committed to
 * {@link #RESOURCE}. This class simply reads it.
 * </p>
 *
 * <p>
 * Nothing about Loom's boot changed: the registry is still populated from
 * {@code ServiceLoader<NodeDescriptorProvider>}, so a fresh install still validates saved pipelines
 * and serves a full palette before any worker has ever connected. Only the source of the data moved,
 * from prose typed twice to prose typed once and derived.
 * </p>
 *
 * <p>
 * The resource is kept honest by {@code NodeSpecGoldenTest}, which re-harvests every annotated node
 * and fails if what it produces differs from what is committed here. A stale resource is therefore a
 * build failure, not a silently wrong palette.
 * </p>
 */
public class GeneratedNodeDescriptorProvider implements NodeDescriptorProvider {

	/** Classpath location of the generated contract set. Regenerated by {@code NodeSpecGoldenTest}'s sibling generator. */
	public static final String RESOURCE = "/node-descriptors.json";

	private static final ObjectMapper MAPPER = new ObjectMapper();

	@Override
	public List<NodeDescriptor> getDescriptors() {
		try (InputStream in = GeneratedNodeDescriptorProvider.class.getResourceAsStream(RESOURCE)) {
			if (in == null) {
				// An empty palette is a catastrophic, quiet failure: every saved pipeline stops
				// validating and the editor offers nothing. Fail loudly at boot instead.
				throw new IllegalStateException("Missing " + RESOURCE + " on the classpath. The built-in node "
					+ "contracts are generated from the annotated node classes; regenerate them and rebuild.");
			}
			return MAPPER.readValue(in, new TypeReference<List<NodeDescriptor>>() {
			});
		} catch (IOException e) {
			throw new IllegalStateException("Could not read the generated node contracts from " + RESOURCE, e);
		}
	}
}
